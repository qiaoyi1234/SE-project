def set_grid(t, widths):
    t.autofit = False
    # 版心宽度 21 - 2.4*2 = 16.2cm，超宽按比例缩，避免表格压到页边距外
    total = sum(widths)
    if total > 16.0:
        widths = [w * 16.0 / total for w in widths]
    tbl = t._tbl
    grid = tbl.find(qn("w:tblGrid"))
    if grid is not None:
        for gc, w in zip(grid.findall(qn("w:gridCol")), widths):
            gc.set(qn("w:w"), str(int(Cm(w).twips)))
    for row in t.rows:
        for i, w in enumerate(widths):
            row.cells[i].width = Cm(w)


def T(headers, rows, widths=None, fsize=9, align_center=False, caption=None):
    if caption:
        CAP(caption)
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ""
        set_run(c.paragraphs[0].add_run(h), ea=EAH, size=fsize, bold=True)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            set_run(p.add_run(str(v)), size=fsize)
            if align_center:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if widths:
        set_grid(t, widths)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


