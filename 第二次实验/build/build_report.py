H("6.4 反思：AI 在设计里能做什么、不能做什么", 2)
B("它能很快把需求“铺开”成结构：模块、表、字段、图都能在几分钟内给出一个像样的初稿，"
  "省下的是“从零开始搭骨架”的时间，这部分大约占整个设计的一半工作量。")
B("它给的是“教科书答案”，不是“你这个项目的答案”。状态模式、悲观锁、全表扫描、AOP 审计，"
  "单看每一条都没错，但放到“单实例、无中间件、要逐条验收”的项目里就不合适。判断合不合适，只能人来。")
B("它不判断“这个约束该由谁保证”。唯一有效预约是用锁还是用唯一索引，本质是“把正确性放在应用层还是数据库层”的取舍，"
  "模型倾向于给应用层的方案，因为它更“面向对象”，但这恰恰是最容易漏的地方。")
B("生成物看起来完整，不代表内部一致。初稿里 M2 和 M4 互相依赖、通知与事务边界不一致、类图大到看不清，"
  "这些都不是“写错了”，而是“没有站在评审者角度检查”。")
B("图的生成成本很低，但“图能不能被看懂”是另一回事。16 张图里，类图和用例图都重画过，"
  "原因是第一版塞了太多东西——这一点模型不会提醒你。")
B("最有用的一次用法其实是“反向检查”：把依赖表发给模型，让它找循环依赖和事务边界问题，它确实指出了 M2/M4 的问题。"
  "让模型当“审稿人”比当“作者”更可靠。")

H("6.5 能不能设计一套“人只做检查校对”的工作流", 2)
P("按这次的实际体验，答案是可以把大部分“产出”交给模型，但有三类判断必须留在人这边。我试着把流程写成六步：")
NUM("准备上下文：把需求基线、非功能约束、技术栈、术语表整理成一份固定输入，每次生成都带上，避免模型自由发挥。")
NUM("分块生成：一次只让它做一件事（先模块、再类图、再时序图、再 UI），不要一次要一整套，否则错了很难定位。")
NUM("规则化自检：用一份固定清单逐项打勾——模块是否覆盖全部需求、依赖是否有环、每个状态转换是否在表里、"
    "事务边界是否覆盖级联、界面是否覆盖异常态。清单里的项目都是可以客观判断的。")
NUM("人工决策点：把模型给的方案和备选方案并列，由人拍板。这次的五处修改（模块、状态机、锁、超时通知、可见性）都属于这一类。")
NUM("回归验证：改完之后回头看图和表是否还一致，比如改了锁方案，时序图、类图、数据表三处都要同步。")
NUM("版本留痕：AI 初稿和人工修改分两次提交，diff 就是审查记录。")
P("三个必须人工的卡点：一是“约束该由谁保证”的取舍（应用层还是数据库层），二是“验收口径能不能对上需求”的判断，"
  "三是“这张图评审时能不能看懂”的判断。前两个错了会在实验三返工，第三个错了会在答辩时被问住。"
  "除此之外的重复劳动——画图、排版、写字段、生成初稿文字——确实可以交给模型，人只需要检查和校对。")
P("所以我的结论是：这套工作流可以把设计阶段的体力活压缩到原来的三分之一左右，"
  "但“检查校对”本身不是被动劳动，要能看出问题，前提是自己先把需求和约束想清楚。"
  "模型负责“给选项”，人负责“做选择并为选择负责”，这条边界在这次实验里体现得很明显。")

