def TWOFIG(p1, c1, n1, p2, c2, n2, width=6.3):
    """两张图并排（用于手机界面）"""
    t = doc.add_table(rows=2, cols=2)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, (path, cap, num) in enumerate(((p1, c1, n1), (p2, c2, n2))):
        cell = t.rows[0].cells[i]
        cell.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        cell.paragraphs[0].add_run().add_picture(path, width=Cm(width))
        c = t.rows[1].cells[i]
        c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        set_run(c.paragraphs[0].add_run(f"图 {num}　{cap}"), ea=EAH, size=8.5)
    set_grid(t, [8.0, 8.0])


